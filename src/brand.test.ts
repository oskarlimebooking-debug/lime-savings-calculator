import { describe, expect, test, vi } from "vitest";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
// next/font/google se v vitestu ne izvede, layout pa potrebujemo zaradi
// izvozenega `metadata`.
vi.mock("next/font/google", () => ({
  Inter: () => ({ variable: "--font-inter", className: "inter" }),
}));

import { metadata } from "./app/layout";

const ROOT = join(__dirname, "..");

/**
 * Prepovedani nizi stare generične palete. Sestavljeni iz delov, da jih
 * straž-test ne najde v sebi — datoteka je namreč tudi v `src/`.
 */
const FORBIDDEN = ["#" + "22c55e", "#" + "16a34a", "lime" + "-500"];

/** Vse izvorne datoteke pod `src/`, rekurzivno. */
function sourceFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? sourceFiles(path) : [path];
  });
}

describe("stara paleta je odstranjena (T3.2)", () => {
  const files = sourceFiles(__dirname);

  test("AC1: nobena datoteka v src/ ne vsebuje stare generične zelene", () => {
    expect(files.length).toBeGreaterThan(20);
    const hits = files.flatMap((file) => {
      const src = readFileSync(file, "utf8");
      return FORBIDDEN.filter((needle) => src.includes(needle)).map(
        (needle) => `${file.slice(ROOT.length + 1)}: ${needle}`,
      );
    });
    expect(hits).toEqual([]);
  });

  test("sage je edina zelena lestvica — lime aliasa ni več", () => {
    const config = readFileSync(join(ROOT, "tailwind.config.ts"), "utf8");
    expect(config).not.toMatch(/\blime\s*:/);
    expect(config).toContain("#548F68");
  });
});

describe("znamka v metapodatkih in public/ (T3.2)", () => {
  test("AC2: layout.tsx nima privzetka ogrodja, naslov pa imenuje Lime", () => {
    const layout = readFileSync(join(__dirname, "app", "layout.tsx"), "utf8");
    expect(layout).not.toContain("Create Next App");
    expect(layout).not.toContain("Generated by create next app");
    expect(typeof metadata.title).toBe("string");
    expect(metadata.title as string).not.toBe("");
    expect(metadata.title as string).toContain("Lime");
    expect(metadata.description ?? "").toContain("Lime");
  });

  test.each(["logo-primary.svg", "favicon-circle.svg"])(
    "AC3: public/%s obstaja in ni prazna",
    (name) => {
      const file = join(ROOT, "public", name);
      expect(statSync(file).size).toBeGreaterThan(0);
      const svg = readFileSync(file, "utf8");
      expect(svg).toContain("<svg");
      // znamka riše s CTA zeleno iz žetonov, ne s poljubno zeleno
      expect(svg).toContain("#548F68");
    },
  );
});

describe("DESIGN.md (T3.2)", () => {
  const doc = readFileSync(join(ROOT, "DESIGN.md"), "utf8");

  test.each(["Barve", "Tipografija", "Površine", "Prepovedi"])(
    "AC4: DESIGN.md ima razdelek %s",
    (section) => {
      expect(doc).toContain(`## ${section}`);
    },
  );
});
