import { Lang } from "./i18n";

/**
 * Price ladder rungs, ascending. The order is load-bearing: the picker walks it
 * to guarantee that every trio mixes a small, a mid and a big-ticket item.
 */
export const TIER_ORDER = ["treat", "small", "mid", "big", "grand", "dream"] as const;

export type RewardTier = (typeof TIER_ORDER)[number];

/** Inclusive-exclusive EUR bounds per tier. Enforced by rewards.test.ts. */
export const TIER_BOUNDS: Record<RewardTier, readonly [number, number]> = {
  treat: [10, 60],
  small: [60, 250],
  mid: [250, 900],
  big: [900, 3000],
  grand: [3000, 12000],
  dream: [12000, 60000],
};

export type RewardCategory =
  | "dining"
  | "tech"
  | "home"
  | "beauty"
  | "experience"
  | "travel"
  | "luxury"
  | "everyday"
  | "business";

export interface Reward {
  /** Stable kebab-case id. React key, analytics property and dedupe key. Never reuse. */
  id: string;
  /** Indicative gross EUR price. Round numbers only — this is a vibe, not a quote. */
  price: number;
  tier: RewardTier;
  category: RewardCategory;
  /** Single emoji rendered as the card's visual. Keeps the feature asset-free. */
  emoji: string;
  /** Brand name shown on the card. Never translated. */
  retailer: string;
  /** Homepage or verified search URL. Never a SKU deep link — those rot within months. */
  url: string;
  /** Nominative singular noun phrase. Rendered as `{qty}× {label}` — see i18n rewards.quantity. */
  label: Record<Lang, string>;
  /** Set when a quantity > 1 reads absurd (a car, a salon refit). Picker forces quantity to 1. */
  singleOnly?: boolean;
}

